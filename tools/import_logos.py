#!/usr/bin/env python3
"""Import Fastfetch's built-in logos into NyFetch.

Usage: python3 -I tools/import_logos.py <path-to-fastfetch-checkout>

Reads  <fastfetch>/src/logo/ascii/*.inc  (metadata) and  <fastfetch>/src/logo/ascii/*/*.txt  (art)
Writes  logos/<name>.txt   (verbatim copies of the art)
        src/logos_data.rs  (static table: names, colors, size/alter flags, art via include_str!)

Fastfetch is MIT licensed (see LICENSE-FASTFETCH). Re-run this script to refresh the logos.
"""
import re
import shutil
import sys
from pathlib import Path

if len(sys.argv) != 2:
    sys.exit(__doc__)

ff = Path(sys.argv[1])
ascii_dir = ff / "src" / "logo" / "ascii"
root = Path(__file__).resolve().parent.parent
out_logos = root / "logos"

# ---- colour macros ----------------------------------------------------------------------
macros = {}
for m in re.finditer(r'#define\s+(FF_COLOR_[A-Z0-9_]+)\s+"([^"]*)"', (ff / "src/common/color.h").read_text()):
    macros[m.group(1)] = m.group(2)


def color_expr(expr: str) -> str:
    """Evaluate a C string-concatenation made of FF_COLOR_* macros and string literals."""
    out = ""
    for tok in re.finditer(r'FF_COLOR_[A-Z0-9_]+|"([^"]*)"', expr):
        if tok.group(1) is not None:
            out += tok.group(1)
        else:
            out += macros[tok.group(0)]
    return out.rstrip(";")


# ---- art files --------------------------------------------------------------------------
art = {}
for p in sorted(ascii_dir.glob("*/*.txt")):
    key = p.stem.upper()
    assert key not in art, f"duplicate logo file stem {key}"
    art[key] = p

if out_logos.exists():
    shutil.rmtree(out_logos)
out_logos.mkdir()
for key, p in art.items():
    shutil.copyfile(p, out_logos / p.name)

# ---- metadata ---------------------------------------------------------------------------
entries = []
for inc in sorted(ascii_dir.glob("*.inc")):
    text = inc.read_text()
    for blk in re.finditer(r"#ifdef FASTFETCH_DATATEXT_LOGO_(\w+)(.*?)#endif", text, re.S):
        macro, body = blk.group(1), blk.group(2)
        names = re.findall(r'"((?:[^"\\]|\\.)*)"', re.search(r"\.names\s*=\s*\{(.*?)\}", body, re.S).group(1))
        lines_macro = re.search(r"\.lines\s*=\s*FASTFETCH_DATATEXT_LOGO_(\w+)", body).group(1)
        colors = [color_expr(c) for c in re.search(r"\.colors\s*=\s*\{(.*?)\}\s*,", body, re.S).group(1).split(",") if c.strip()]
        ck = re.search(r"\.colorKeys\s*=\s*(.*?),\s*\n", body)
        ct = re.search(r"\.colorTitle\s*=\s*(.*?),\s*\n", body)
        ty = re.search(r"\.type\s*=\s*(.*?),\s*\n", body)
        flags = 0
        if ty:
            if "SMALL_BIT" in ty.group(1):
                flags |= 1
            if "ALTER_BIT" in ty.group(1):
                flags |= 2
        assert lines_macro in art, f"missing art for {lines_macro}"
        entries.append(
            dict(
                names=names,
                colors=colors,
                key=color_expr(ck.group(1)) if ck else None,
                title=color_expr(ct.group(1)) if ct else None,
                flags=flags,
                file=art[lines_macro].name,
            )
        )

used = {e["file"] for e in entries}
unused = sorted(set(p.name for p in art.values()) - used - {"unknown.txt"})


def q(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def opt(s):
    return f"Some({q(s)})" if s is not None else "None"


with open(root / "src" / "logos_data.rs", "w") as f:
    f.write("// @generated by tools/import_logos.py from Fastfetch (MIT). Do not edit by hand.\n")
    f.write("use crate::logo::LogoDef;\n\n")
    f.write("pub static UNKNOWN: LogoDef = LogoDef {\n    names: &[\"unknown\"],\n    colors: &[\"39\"],\n")
    f.write("    key_color: None,\n    title_color: None,\n    flags: 0,\n")
    f.write('    art: include_str!("../logos/unknown.txt"),\n};\n\n')
    f.write("pub static LOGOS: &[LogoDef] = &[\n")
    for e in entries:
        f.write("    LogoDef {\n")
        f.write(f"        names: &[{', '.join(q(n) for n in e['names'])}],\n")
        f.write(f"        colors: &[{', '.join(q(c) for c in e['colors'])}],\n")
        f.write(f"        key_color: {opt(e['key'])},\n")
        f.write(f"        title_color: {opt(e['title'])},\n")
        f.write(f"        flags: {e['flags']},\n")
        f.write(f"        art: include_str!(\"../logos/{e['file']}\"),\n")
        f.write("    },\n")
    f.write("];\n")

shutil.copyfile(ff / "LICENSE", root / "LICENSE-FASTFETCH")
print(f"imported {len(entries)} logo entries, {len(art)} art files; {len(unused)} art files have no entry: {unused[:5]}")
